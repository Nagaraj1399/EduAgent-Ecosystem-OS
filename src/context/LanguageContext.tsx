interface LanguageContextType {
  language: LanguageType;
  setLanguage: (lang: LanguageType) => void;
  t: (key: string, fallback?: string) => string;
  translateDynamicText: (text: string, targetLang?: LanguageType) => Promise<string>;
  supportedLanguages: LanguageOption[];
  isTranslating: boolean;
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<LanguageType>(() => {
    if (typeof window !== 'undefined') {
      const saved = localStorage.getItem('eduagent_os_language') as LanguageType;
      if (saved && SUPPORTED_LANGUAGES.some((l) => l.id === saved)) {
        return saved;
      }
    }
    return 'English';
  });

  const [isTranslating, setIsTranslating] = useState<boolean>(false);
  const [dynamicCache, setDynamicCache] = useState<Record<string, string>>(() => {
    if (typeof window !== 'undefined') {
      try {
        const saved = localStorage.getItem('eduagent_translation_cache');
        if (saved) return JSON.parse(saved);
      } catch (e) {}
    }
    return {};
  });

  const pendingRequestsRef = useRef<Set<string>>(new Set());
  const batchQueueRef = useRef<{ text: string; lang: LanguageType }[]>([]);
  const batchTimerRef = useRef<NodeJS.Timeout | null>(null);

  const flushBatch = useCallback(() => {
    if (batchQueueRef.current.length === 0) return;

    const itemsToProcess = [...batchQueueRef.current];
    batchQueueRef.current = [];

    // Group items by target language
    const langGroups: Record<string, string[]> = {};
    for (const item of itemsToProcess) {
      if (!langGroups[item.lang]) {
        langGroups[item.lang] = [];
      }
      if (!langGroups[item.lang].includes(item.text)) {
        langGroups[item.lang].push(item.text);
      }
    }

    // Process each language group in a single bulk request
    Object.entries(langGroups).forEach(([targetLang, texts]) => {
      fetch('/api/ai/translate', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ texts, targetLanguage: targetLang }),
      })
        .then((res) => (res.ok ? res.json() : null))
        .then((data) => {
          if (data && Array.isArray(data.translations)) {
            setDynamicCache((prev) => {
              const next = { ...prev };
              texts.forEach((origText, idx) => {
                const tr = data.translations[idx];
                if (tr) {
                  next[`${targetLang}:${origText}`] = tr;
                }
              });
              try {
                localStorage.setItem('eduagent_translation_cache', JSON.stringify(next));
              } catch (e) {}
              return next;
            });
          }
        })
        .catch(() => {})
        .finally(() => {
          texts.forEach((txt) => pendingRequestsRef.current.delete(`${targetLang}:${txt}`));
        });
    });
  }, []);

  const requestDynamicTranslation = useCallback(
    (textToTranslate: string, targetLang: LanguageType) => {
      if (!textToTranslate || targetLang === 'English') return;
      const cacheKey = `${targetLang}:${textToTranslate}`;
      if (pendingRequestsRef.current.has(cacheKey)) return;

      pendingRequestsRef.current.add(cacheKey);
      batchQueueRef.current.push({ text: textToTranslate, lang: targetLang });

      if (batchTimerRef.current) {
        clearTimeout(batchTimerRef.current);
      }

      batchTimerRef.current = setTimeout(() => {
        flushBatch();
      }, 200);
    },
    [flushBatch]
  );

  const setLanguage = (newLang: LanguageType) => {
    setLanguageState(newLang);
    if (typeof window !== 'undefined') {
      const code = SUPPORTED_LANGUAGES.find((l) => l.id === newLang)?.code || 'en';
      localStorage.setItem('eduagent_os_language', newLang);
      localStorage.setItem('eduagent_lang', code);
      document.documentElement.lang = code;
      window.dispatchEvent(new Event('languagechange'));
      window.dispatchEvent(new CustomEvent('eduagent_language_changed', { detail: { language: newLang } }));
    }
  };

  useEffect(() => {
    const code = SUPPORTED_LANGUAGES.find((l) => l.id === language)?.code || 'en';
    if (typeof window !== 'undefined') {
      localStorage.setItem('eduagent_lang', code);
      document.documentElement.lang = code;
    }
  }, [language]);

  useEffect(() => {
    const handleStorageChange = () => {
      window.dispatchEvent(new Event('languagechange'));
      const langCode = localStorage.getItem('eduagent_lang') || 'en';
      document.documentElement.lang = langCode;

      const savedOsLang = localStorage.getItem('eduagent_os_language') as LanguageType;
      if (savedOsLang && SUPPORTED_LANGUAGES.some((l) => l.id === savedOsLang)) {
        setLanguageState(savedOsLang);
      } else if (langCode) {
        const found = SUPPORTED_LANGUAGES.find((l) => l.code === langCode);
        if (found) {
          setLanguageState(found.id);
        }
      }
    };

    window.addEventListener('storage', handleStorageChange);
    return () => window.removeEventListener('storage', handleStorageChange);
  }, []);

  // Instant zero-lag dictionary lookup with automatic Gemini dynamic fallback
  const t = useCallback(
    (key: string, fallback?: string): string => {
      const langDict = UI_DICTIONARY[language];
      if (langDict && langDict[key]) {
        return langDict[key];
      }
      if (fallback && langDict && langDict[fallback]) {
        return langDict[fallback];
      }

      // Check dynamic cache
      const cacheKey = `${language}:${key}`;
      if (dynamicCache[cacheKey]) {
        return dynamicCache[cacheKey];
      }

      if (fallback) {
        const fallbackCacheKey = `${language}:${fallback}`;
        if (dynamicCache[fallbackCacheKey]) {
          return dynamicCache[fallbackCacheKey];
        }
      }

      // Automatically dispatch background Gemini translation if language is not English
      if (language !== 'English' && typeof window !== 'undefined') {
        const textToTranslate = fallback || key;
        if (textToTranslate && textToTranslate.trim().length > 0) {
          requestDynamicTranslation(textToTranslate, language);
        }
      }

      return fallback || key;
    },
    [language, dynamicCache, requestDynamicTranslation]
  );

  // Direct Gemini-Powered Dynamic Translation method
  const translateDynamicText = useCallback(
    async (text: string, targetLang: LanguageType = language): Promise<string> => {
      if (!text || targetLang === 'English') return text;

      const cacheKey = `${targetLang}:${text}`;
      if (dynamicCache[cacheKey]) {
        return dynamicCache[cacheKey];
      }

      try {
        setIsTranslating(true);
        const res = await fetch('/api/ai/translate', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ text, targetLanguage: targetLang }),
        });

        if (res.ok) {
          const data = await res.json();
          if (data && data.translatedText) {
            setDynamicCache((prev) => {
              const next = { ...prev, [cacheKey]: data.translatedText };
              try {
                localStorage.setItem('eduagent_translation_cache', JSON.stringify(next));
              } catch (e) {}
              return next;
            });
            return data.translatedText;
          }
        }
      } catch (err) {
        console.warn('Dynamic Gemini translation failed, returning original:', err);
      } finally {
        setIsTranslating(false);
      }

      return text;
    },
    [language, dynamicCache]
  );

  return (
    <LanguageContext.Provider
      value={{
        language,
        setLanguage,
        t,
        translateDynamicText,
        supportedLanguages: SUPPORTED_LANGUAGES,
        isTranslating,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};
